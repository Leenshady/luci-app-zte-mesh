#!/usr/bin/env python3
"""mkprofile.py SNAPSHOT [OUT]: turn a vendor `sendcmd 1 DB p` snapshot into the shim's /run/zte-mesh/db-profile
(lines 'TABLE ROW FIELD VALUE'). Only persistent (isSave=1) non-empty fields of the policy tables the shim loads at startup.
Fields the service sets itself (identity, role, V2, market sign, BSS/ESSID matching) are left out so explicit config keeps winning."""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from snapdb import parse
db = parse(sys.argv[1])
SKIP = {"MultiAPMaster": {"ViewName"}, "MultiAPDomain": {"ViewName", "ESSID", "DomainUsed", "BsActive"},
        "P1905ComCfg": {"Enable", "MarketConfEn", "MarketSign"},
        # the shim fills these two itself (same baseline values); the profile can still override the rest
        "MultiAPRoamCatonCfg": set(), "WLANSetting": {"ViewName", "DualBandSync", "MLOEnable"},
        # MultiAPCfg: the shim sets role/identity fields itself (SR1010 role = controller only), keep those
        "MultiAPCfg": {"Mode", "Enable", "SetRoleEnable", "RoleElect", "EnMasterOnly", "IFLink", "VersionMode", "SSIDSyncRadio",
                       "CurHop", "MaxHop", "P1905DevNum", "WANForward", "AcdPubKeyReset", "AcdPubKeyAuth"}}
out = []
for tbl, skip in SKIP.items():
    for r, row in enumerate(db[tbl]):
        for f, (v, save) in row.items():
            if save == "1" and f not in skip and v != "" and " " not in f:
                out.append("%s %d %s %s" % (tbl, r, f, v))
text = "# generated by mkprofile.py from a vendor DB snapshot\n" + "\n".join(out) + "\n"
(open(sys.argv[2], "w") if len(sys.argv) > 2 else sys.stdout).write(text)
print("%d lines" % len(out), file=sys.stderr)
